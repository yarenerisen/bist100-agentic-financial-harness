def md(df, floatfmt=2):
    cols = list(df.columns)
    fmt = lambda v: "" if v is None or (isinstance(v, float) and np.isnan(v)) else (f"{v:.{floatfmt}f}" if isinstance(v, float) else str(v))
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def write(name, title, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(f"# {title}\n\n_Generated by `bist_llm/research/run_scenarios.py` on {time.strftime('%Y-%m-%d')}; "
                            f"data 2024-01-01 – {CUT}; analysis date {CUT}. Historical, educational results only._\n\n{body}\n")
    print("wrote", OUT / name)


# ------------------------------------------------------------------ 1 sector catch-up
def sector_catchup():
    rows = []
    for sec, tk in core.SECTORS.items():
        tk = [t for t in tk if t in core.available_tickers()]
        if len(tk) < 3:
            continue
        for strong in (False, True):
            r = core.run_backtest_catch_up(sec, "2024-01-01", CUT, require_strong_sector=strong)
            p = r["pooled_all_stocks"]
            pb = backtest.run_strategy_backtest("sector_catch_up", sec, "2024-01-01", CUT, 10, sector=sec, require_strong_sector=strong)
            perf = {x["series"]: x for x in pb["performance"]}
            rows.append({"sector": sec, "stocks": len(tk), "strong_sector_filter": strong,
                         "events_20d": p["20d"]["events"], "hit_5d_%": p["5d"]["hit_rate_pct"], "hit_10d_%": p["10d"]["hit_rate_pct"],
                         "hit_20d_%": p["20d"]["hit_rate_pct"], "false_pos_20d_%": p["20d"]["false_positive_rate_pct"],
                         "mean_rel_20d_pp": p["20d"]["mean_rel_return_pp"], "trades": pb["trades"],
                         "strategy_%": perf["strategy"]["cumulative_return_pct"], "buy_hold_%": perf["buy_and_hold_equal_weight"]["cumulative_return_pct"],
                         "XU100_%": perf["XU100"]["cumulative_return_pct"], "sharpe": perf["strategy"]["sharpe_ratio"], "max_dd_%": perf["strategy"]["max_drawdown_pct"]})
    df = pd.DataFrame(rows)
    avg = df[~df.strong_sector_filter][["hit_20d_%", "false_pos_20d_%"]].mean()
    body = ("Rule: a stock lags its sector median by ≥ 5 pp over 20 trading days (non-overlapping events). Hit = it beats the peer median "
            "over the next h days; false positive = it keeps underperforming. Portfolio: enter next open, hold 10 days, 0.2% commission + 0.05% slippage per side.\n\n"
            + md(df) + f"\n\n**Finding.** Without the strong-sector filter the average 20-day hit rate across sectors is {avg['hit_20d_%']:.1f}% and the false-positive rate "
            f"{avg['false_pos_20d_%']:.1f}%: relative weakness mostly did **not** mean-revert within 20 days in this period. Compare each strategy row with buy-and-hold "
            "before calling any laggard a catch-up candidate; this is why the harness labels most laggards WATCH / REJECT_SIGNAL.")
    write("01_sector_catch_up.md", "Scenario 1 — Sector laggard / catch-up", body)


# ------------------------------------------------------------------ 2 weekday patterns + multiple testing
def weekday():
    pats = ["".join(p) for p in itertools.product("UD", repeat=5)]
    rec = []
    for t in UNIVERSE:
        for p in pats:
            i = core.test_weekday_pattern(t, p, "2024-01-01", "2025-12-31")
            o = core.test_weekday_pattern(t, p, "2026-01-01", CUT)
            rec.append({"ticker": t, "pattern": p, "is_n": i["pattern_occurrences"], "is_p": i["binomial_p_value_one_sided"],
                        "oos_n": o["pattern_occurrences"], "oos_p": o["binomial_p_value_one_sided"]})
    d = pd.DataFrame(rec)
    tests = len(d)
    s05 = d[d.is_p < 0.05]; sb = d[d.is_p < 0.05 / 32]
    surv = s05[s05.oos_p < 0.05]
    mt = pd.DataFrame([{"tests_in_sample": tests, "expected_false_positives_at_5%": round(tests * 0.05, 1),
                        "significant_p<0.05": len(s05), "significant_after_Bonferroni(p<0.0016)": len(sb),
                        "of_p<0.05_still_p<0.05_out_of_sample": len(surv)}])
    dd = []
    for t in UNIVERSE:
        i = core.test_weekday_pattern(t, "DDDUU", "2024-01-01", "2025-12-31"); o = core.test_weekday_pattern(t, "DDDUU", "2026-01-01", CUT)
        dd.append({"ticker": t, "IS_occurrences": i["pattern_occurrences"], "IS_weeks": i["complete_weeks"], "IS_p": i["binomial_p_value_one_sided"],
                   "IS_tradable_ThuFri_after_cost_%": i["tradable_thu_fri_mean_after_cost_pct"], "OOS_occurrences": o["pattern_occurrences"],
                   "OOS_p": o["binomial_p_value_one_sided"], "OOS_tradable_ThuFri_after_cost_%": o["tradable_thu_fri_mean_after_cost_pct"]})
    body = ("### Multiple-testing experiment\nAll 32 Mon–Fri up/down patterns were tested for all 30 stocks in-sample (2024–2025), then re-tested out-of-sample (2026-01-01 – 2026-09-10).\n\n"
            + md(mt) + "\n\nIf patterns were pure noise we would expect about 5% of tests to look 'significant' at p < 0.05. Compare that with the observed count and with "
            "how few survive out of sample: searching many patterns manufactures false discoveries.\n\n"
            + ("Patterns significant in-sample at p < 0.05 that stayed significant out of sample:\n\n" + md(surv) if len(surv) else "No in-sample pattern stayed significant out of sample.")
            + "\n\n### 'Mon–Tue–Wed down, Thu–Fri up' (DDDUU) for every stock\n" + md(pd.DataFrame(dd), 3))
    write("02_weekday_patterns.md", "Scenario 2 — Weekday and multi-day patterns", body)


# ------------------------------------------------------------------ 3 technical reversal events
def reversals():
    rows = []
    for ev in events.EVENTS:
        agg = {"n": 0, "succ": 0, "r5": [], "rise_n": 0, "rise_s": 0, "fall_n": 0, "fall_s": 0, "hv_n": 0, "hv_s": 0}
        for t in UNIVERSE:
            g = events.detect_reversal_events(t, ev)["groups"]
            a = g["all_events"]
            agg["n"] += a["events_with_complete_window"]; agg["succ"] += a.get("success_count", 0)
            if a.get("mean_return_5d_pct") is not None:
                agg["r5"] += [a["mean_return_5d_pct"]] * a["events_with_complete_window"]
            for k, key in (("rise", "regime_xu100_rising"), ("fall", "regime_xu100_falling"), ("hv", "regime_high_volatility")):
                agg[f"{k}_n"] += g[key]["events_with_complete_window"]; agg[f"{k}_s"] += g[key].get("success_count", 0)
        pct = lambda s, n: round(100 * s / n, 1) if n else None
        rows.append({"event": ev, "expected_direction": "up" if events.EVENTS[ev][0] > 0 else "down", "events": agg["n"],
                     "success_rate_%": pct(agg["succ"], agg["n"]), "mean_5d_return_%": round(float(np.mean(agg["r5"])), 2) if agg["r5"] else None,
                     "success_XU100_rising_%": pct(agg["rise_s"], agg["rise_n"]), "success_XU100_falling_%": pct(agg["fall_s"], agg["fall_n"]),
                     "success_high_vol_%": pct(agg["hv_s"], agg["hv_n"])})
    bt = []
    for ev in ("lower_bollinger_touch", "rsi_trough", "supertrend_bullish_flip", "kama_cross_up", "ichimoku_cloud_breakout"):
        r = backtest.run_strategy_backtest(ev, UNIVERSE, "2024-01-01", CUT, 5)
        perf = {x["series"]: x for x in r["performance"]}
        bt.append({"strategy": ev, "trades": r["trades"], "win_rate_%": r["win_rate_pct"], "strategy_%": perf["strategy"]["cumulative_return_pct"],
                   "sharpe": perf["strategy"]["sharpe_ratio"], "max_dd_%": perf["strategy"]["max_drawdown_pct"],
                   "buy_hold_%": perf["buy_and_hold_equal_weight"]["cumulative_return_pct"], "XU100_%": perf["XU100"]["cumulative_return_pct"]})
    body = ("Pooled over the 30-stock universe, 2024-01-01 – 2026-09-10. Success = price moves in the expected direction within 5 trading days; "
            "events whose 5-day window is incomplete at the analysis date are excluded. Regime = sign of XU100 20-day return; high volatility = ATR% above its 120-day median.\n\n"
            + md(pd.DataFrame(rows)) + "\n\n### Event strategies as trades (enter next open, hold 5 days, costs + slippage), equal-weight across the universe\n" + md(pd.DataFrame(bt))
            + "\n\nCompare success rates with the stock's unconditional up-day frequency (~50%) and the trade results with buy-and-hold: "
              "a high hit rate does not imply a profitable strategy (Prediction ≠ profitable strategy).")
    write("03_technical_reversals.md", "Scenario 3 — Technical reversal events", body)


# ------------------------------------------------------------------ 4 fundamentals and price reaction
def fundamentals():
    f = pd.read_csv(macro_fund.FUND_CSV).dropna(subset=["revenue", "ebitda"])
    rows, pool = [], {"improving": [], "not_improving": []}
    for t in sorted(f.ticker.unique()):
        r = macro_fund.calculate_fundamental_change(t, "2024-01-01", CUT)
        qs = r["quarters"]
        for q in qs:
            w = q["post_disclosure"]["20d"]
            if w["complete"]:
                pool["improving" if q["improving"] else "not_improving"].append(w["abnormal_vs_xu100_pp"])
        g = r["improving_vs_not_20d"]
        rows.append({"ticker": t, "quarters": len(qs), "incomplete_20d": sum(1 for q in qs if not q["post_disclosure"]["20d"]["complete"]),
                     "latest_ebitda_margin_%": qs[-1]["ebitda_margin_pct"] if qs else None, "latest_nd_ebitda": qs[-1]["net_debt_to_ebitda"] if qs else None,
                     "improving_q": g["improving"]["quarters"], "improving_abn20_pp": g["improving"]["mean_abnormal_20d_vs_xu100_pp"],
                     "other_q": g["not_improving"]["quarters"], "other_abn20_pp": g["not_improving"]["mean_abnormal_20d_vs_xu100_pp"]})
    pl = pd.DataFrame([{"group": k, "quarters": len(v), "mean_abnormal_20d_vs_XU100_pp": round(float(np.mean(v)), 2) if v else None,
                        "median_pp": round(float(np.median(v)), 2) if v else None, "share_positive_%": round(100 * float(np.mean(np.array(v) > 0)), 1) if v else None}
                       for k, v in pool.items()])
    body = ("Source: KAP financial-report PDFs (reports 2024Q4 – 2026Q2), parsed by `data/parse_financials.py`. Returns start at the last close on/before the "
            "board-approval (disclosure) date; abnormal = stock − XU100. 'Improving' = EBITDA margin up QoQ and Net Debt/EBITDA not up.\n\n"
            + md(pd.DataFrame(rows)) + "\n\n### Pooled\n" + md(pl)
            + "\n\nSmall samples (≈ 6 quarters per company); the comparison is an association, not a causal effect. Banks (AKBNK) are excluded because EBITDA-based ratios are not meaningful for them.")
    write("04_fundamentals_price_reaction.md", "Scenario 4 — Quarterly fundamentals and price reaction", body)


# ------------------------------------------------------------------ macro + strategy variants
def macro_and_variants():
    rows = []
    for t in UNIVERSE:
        m = macro_fund.get_macro_context("2024-01-01", CUT, ticker=t)
        w = m.get(f"{t}_vs_USDTRY_weekly", {})
        rows.append({"ticker": t, "sector": core.SECTOR_OF.get(t), "weekly_corr_USDTRY": w.get("correlation"), "beta": w.get("beta"),
                     "mean_wk_ret_when_USDTRY_up_%": w.get("mean_stock_return_when_usdtry_up_pct"),
                     "mean_wk_ret_when_USDTRY_down_%": w.get("mean_stock_return_when_usdtry_down_pct")})
    m = macro_fund.get_macro_context("2024-01-01", CUT)
    fx, pr, fed = m["series"]["USDTRY"], m["tcmb_policy_rate"], m["fed_funds_rate"]
    body = (f"USD/TRY {fx['first']} → {fx['last']} ({fx['change_pct']}%); TCMB policy rate {pr['level_at_start']}% → {pr['level_at_end']}%; "
            f"Fed funds upper bound {fed['level_at_start']}% → {fed['level_at_end']}% (2024-01-01 – {CUT}).\n\n"
            + md(pd.DataFrame(rows).sort_values("weekly_corr_USDTRY"), 3)
            + "\n\nWeekly correlations with USD/TRY are weak for most stocks; 'exporter = rises with the dollar' is not supported as a rule. Correlation ≠ causation.")
    write("05_macro_context.md", "Macro context — FX and policy rates", body)
    f = pd.read_csv(macro_fund.FUND_CSV).dropna(subset=["revenue"])
    tk = sorted(f.ticker.unique())
    r = backtest.preview_strategy_variants(tk, "2024-01-01", CUT, "2026-01-01")
    vr = []
    for k, v in r["variants"].items():
        if not v["available"]:
            vr.append({"variant": k, "definition": v["definition"], "IS_trades": None}); continue
        i, o = v["in_sample"], v["out_of_sample"]
        vr.append({"variant": k, "definition": v["definition"], "IS_trades": i["trades"], "IS_return_%": i["cumulative_return_pct"], "IS_sharpe": i["sharpe_ratio"],
                   "OOS_trades": o["trades"], "OOS_return_%": o["cumulative_return_pct"], "OOS_sharpe": o["sharpe_ratio"],
                   "OOS_buy_hold_%": o["buy_and_hold_return_pct"], "OOS_XU100_%": o["xu100_return_pct"]})
    body = (f"Universe: the {len(tk)} companies with parsed fundamentals ({', '.join(tk)}). In-sample {r['in_sample'][0]} – {r['in_sample'][1]}, "
            f"out-of-sample {r['out_of_sample'][0]} – {r['out_of_sample'][1]}. {r['execution']}.\n\n" + md(pd.DataFrame(vr))
            + "\n\nWarnings: " + "; ".join(r["warnings"]) + "\n\nEach added evidence layer filters signals; fewer trades means lower statistical power. "
              "Fundamentals only start with the 2024Q4 report (disclosed Feb–Mar 2025), so variant C/D cannot trade before that.")
    write("06_strategy_variants.md", "Previewable strategy space — variants A–E", body)


