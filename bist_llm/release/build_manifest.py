"""Builds release/manifest.json: one manifest listing every released file with its SHA-256.
Usage (from bist_llm/):
  python -m release.build_manifest --adapter /path/to/qwen35-4b-lora \
      --traces release/execution_traces.json --base-revision <HF commit of Qwen/Qwen3.5-4B>
The base-model revision is printed by: python -c "from huggingface_hub import model_info; print(model_info('Qwen/Qwen3.5-4B').sha)" """
import argparse, hashlib, json, subprocess, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def entry(p, **extra):
    p = Path(p)
    d = {"path": str(p.resolve().relative_to(REPO)) if REPO in p.resolve().parents else str(p), "sha256": sha(p), "bytes": p.stat().st_size}
    d.update(extra)
    return d


def jsonl_count(p):
    return sum(1 for l in open(p) if l.strip())


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--adapter", required=True, help="LoRA adapter folder (adapter_model.safetensors + adapter_config.json)")
    ap.add_argument("--traces", default=str(ROOT / "release" / "execution_traces.json"))
    ap.add_argument("--base-model", default="Qwen/Qwen3.5-4B")
    ap.add_argument("--base-revision", default=None, help="Hugging Face commit hash of the base model")
    ap.add_argument("--out", default=str(ROOT / "release" / "manifest.json"))
    a = ap.parse_args()
    ad = Path(a.adapter)
    cfg = json.loads((ad / "adapter_config.json").read_text())
    report = ad / "training_report.json"
    code = sorted([p for p in ROOT.rglob("*.py") if "__pycache__" not in p.parts])
    commit = subprocess.run(["git", "describe", "--always", "--dirty", "--abbrev=40"], cwd=REPO, capture_output=True, text=True).stdout.strip()
    traces = json.loads(Path(a.traces).read_text()) if Path(a.traces).exists() else None
    m = {
        "project": "BIST-Analyst: fine-tuned local LLM orchestrating deterministic financial-analysis tools",
        "repository": "https://github.com/yarenerisen/bist100-agentic-financial-harness", "code_commit": commit,
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "analysis_date": "2026-09-10",
        "base_model": {"name": a.base_model, "revision": a.base_revision, "source": f"https://huggingface.co/{a.base_model}",
                       "license": "Apache-2.0", "adapter_config_base": cfg.get("base_model_name_or_path")},
        "model_weights": {"type": "LoRA adapter only", "format": "safetensors",
                          "adapter": entry(ad / "adapter_model.safetensors"), "adapter_config": entry(ad / "adapter_config.json"),
                          "lora": {k: cfg.get(k) for k in ("r", "lora_alpha", "lora_dropout", "target_modules", "peft_type")}},
        "fine_tuning": {"train": entry(ROOT / "training/train.jsonl", examples=jsonl_count(ROOT / "training/train.jsonl")),
                        "validation": entry(ROOT / "training/val.jsonl", examples=jsonl_count(ROOT / "training/val.jsonl")),
                        "test": entry(ROOT / "training/test.jsonl", examples=jsonl_count(ROOT / "training/test.jsonl")),
                        "config_and_hyperparameters": entry(report) if report.exists() else None,
                        "hyperparameters": json.loads(report.read_text()).get("hyperparameters") if report.exists() else None,
                        "system_prompt": entry(ROOT / "training/prompts.py"), "labeling_rules": entry(ROOT / "training/labeling_rules.md"),
                        "generator": entry(ROOT / "training/generate_dataset.py"),
                        "note": "answers in the training data are rule-based templates filled only with numbers copied from real tool outputs"},
        "rag": {"knowledge_base": entry(ROOT / "release/knowledge_base.json"),
                "retrieval": "deterministic tool-based retrieval over timestamped structured sources (no vector store)"},
        "execution_traces": (entry(Path(a.traces), scenarios=traces.get("n"), summary=traces.get("summary")) if traces else None),
        "source_code": {"files": [entry(p) for p in code], "entry_points": {
            "ask_a_question": "python -m harness.run_agent --backend hf --model <adapter> --load-4bit \"<question>\"",
            "five_scenarios": "python -m release.make_traces --backend hf --model <adapter> --load-4bit",
            "live_question": "python -m release.make_traces --backend hf --model <adapter> --load-4bit --question \"<question>\" --out release/live_trace.json",
            "evaluation": "python -m harness.evaluate --backend hf --model <adapter> --load-4bit --limit 40"}},
        "integrity": {"no_question_specific_answers": "the harness has no question-to-answer mapping; every answer is generated by the model "
                                                      "from tool outputs (answer_source=model or model_after_validation_retry)",
                      "harness_fallback": "if the model's answer fails validation twice, or the risk gate holds back an unverified candidate, the harness "
                                          "returns a generic ANALYSIS_UNSAFE / INVESTIGATE notice; "
                                          "such answers are labelled answer_source=harness_fallback in the trace and are never presented as model output",
                      "numbers": "every number in an accepted answer must appear in a tool output (harness/validate.py)"},
    }
    Path(a.out).write_text(json.dumps(m, ensure_ascii=False, indent=1, default=str))
    print("saved", a.out, "| code files:", len(code), "| traces:", bool(traces))
